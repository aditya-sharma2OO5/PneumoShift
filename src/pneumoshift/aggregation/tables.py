def _escape_latex(val: Any) -> str:
    """Escapes text for LaTeX tabular format while preserving math symbols."""
    s = str(val)
    if not s or s == "nan" or s == "None":
        return "-"
    # If the value is a math expression inside $...$, preserve math content
    if s.startswith("$") and s.endswith("$"):
        return s
    # Replace +- with \pm
    s = s.replace("+-", r"\pm ")
    s = s.replace("+/-", r"\pm ")
    # Escape % and _ and &
    s = s.replace("%", r"\%")
    s = s.replace("_", r"\_")
    s = s.replace("&", r"\&")
    return s


def dataframe_to_latex(
    df: pd.DataFrame,
    caption: str = "PneumoShift Master Table",
    label: str = "tab:master",
) -> str:
    """Converts a pandas DataFrame into publication-ready LaTeX with booktabs formatting.

    Args:
        df: Input DataFrame.
        caption: Table caption.
        label: Table label for cross-referencing.

    Returns:
        Formatted LaTeX table string.
    """
    cols = df.columns.tolist()
    # Left align text columns, center numeric columns
    col_alignments = []
    for c in cols:
        sample_vals = df[c].dropna().astype(str).tolist()
        is_num = all(re.match(r"^[-+]?[0-9]*\.?[0-9]+", v) or v in ["-", "nan", "None"] for v in sample_vals[:5]) if sample_vals else False
        col_alignments.append("c" if is_num else "l")
    align_str = "".join(col_alignments)

    lines = [
        r"% Auto-generated by PneumoShift Phase 6 Table Generator",
        r"\begin{table}[htbp]",
        r"\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{align_str}}}",
        r"\toprule",
    ]

    # Header
    header_cells = [_escape_latex(c) for c in cols]
    lines.append(" & ".join(header_cells) + r" \\")
    lines.append(r"\midrule")

    # Data rows
    for _, row in df.iterrows():
        row_cells = [_escape_latex(row[c]) for c in cols]
        lines.append(" & ".join(row_cells) + r" \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    lines.append("")

    return "\n".join(lines)


def dataframe_to_markdown(
    df: pd.DataFrame,
    title: str = "PneumoShift Master Table",
) -> str:
    """Converts a pandas DataFrame into GitHub-flavored Markdown table."""
    cols = df.columns.tolist()
    lines = [
        f"### {title}",
        "",
        "| " + " | ".join(cols) + " |",
        "| " + " | ".join([":---:" if i > 0 else ":---" for i in range(len(cols))]) + " |",
    ]

    for _, row in df.iterrows():
        cells = [str(row[c]) if pd.notna(row[c]) else "-" for c in cols]
        lines.append("| " + " | ".join(cells) + " |")

    lines.append("")
    return "\n".join(lines)



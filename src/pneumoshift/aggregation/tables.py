def build_table6_hypothesis_testing(
    manifest: Dict[str, Any],
    hypothesis_records: Optional[List[HypothesisTestRecord]] = None,
) -> pd.DataFrame:
    """Builds Table 6: Consolidated Hypothesis Testing & Significance Summary."""
    if hypothesis_records is None:
        hypothesis_records = evaluate_study_hypotheses(manifest)

    rows = []
    for r in hypothesis_records:
        effect_str = f"{r.effect_size:+.3f}" if abs(r.effect_size) < 10 else f"{r.effect_size:+.1f}%"
        verdict = "REJECT H0 (PASS)" if r.is_significant else "FAIL TO REJECT"
        rows.append({
            "Hypothesis ID": r.hypothesis_id,
            "Research Question": r.name.replace("_", " "),
            "Null Hypothesis (H0)": r.null_hypothesis,
            "Statistical Test": r.test_type,
            "Effect Size / Difference": effect_str,
            "Raw p-value": f"{r.raw_p_value:.4f}",
            "FDR q-value": f"{r.fdr_q_value:.4f}",
            "Significance Verdict (alpha=0.05)": verdict,
        })

    return pd.DataFrame(rows)


